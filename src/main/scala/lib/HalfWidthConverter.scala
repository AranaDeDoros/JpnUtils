package lib

/** **
  * Half-width converter for Japanese text
  */
object HalfWidthConverter:

  // fullwidth → halfwidth
  private val kanaMap: Map[Char, String] = Map(
    'ア' -> "ｱ", 'イ' -> "ｲ", 'ウ' -> "ｳ", 'エ' -> "ｴ", 'オ' -> "ｵ",
    'カ' -> "ｶ", 'キ' -> "ｷ", 'ク' -> "ｸ", 'ケ' -> "ｹ", 'コ' -> "ｺ",
    'サ' -> "ｻ", 'シ' -> "ｼ", 'ス' -> "ｽ", 'セ' -> "ｾ", 'ソ' -> "ｿ",
    'タ' -> "ﾀ", 'チ' -> "ﾁ", 'ツ' -> "ﾂ", 'テ' -> "ﾃ", 'ト' -> "ﾄ",
    'ナ' -> "ﾅ", 'ニ' -> "ﾆ", 'ヌ' -> "ﾇ", 'ネ' -> "ﾈ", 'ノ' -> "ﾉ",
    'ハ' -> "ﾊ", 'ヒ' -> "ﾋ", 'フ' -> "ﾌ", 'ヘ' -> "ﾍ", 'ホ' -> "ﾎ",
    'マ' -> "ﾏ", 'ミ' -> "ﾐ", 'ム' -> "ﾑ", 'メ' -> "ﾒ", 'モ' -> "ﾓ",
    'ヤ' -> "ﾔ", 'ユ' -> "ﾕ", 'ヨ' -> "ﾖ",
    'ラ' -> "ﾗ", 'リ' -> "ﾘ", 'ル' -> "ﾙ", 'レ' -> "ﾚ", 'ロ' -> "ﾛ",
    'ワ' -> "ﾜ", 'ヲ' -> "ｦ", 'ン' -> "ﾝ",
    'ァ' -> "ｧ", 'ィ' -> "ｨ", 'ゥ' -> "ｩ", 'ェ' -> "ｪ", 'ォ' -> "ｫ",
    'ッ' -> "ｯ", 'ャ' -> "ｬ", 'ュ' -> "ｭ", 'ョ' -> "ｮ",

    // dakuten
    'ガ' -> "ｶﾞ", 'ギ' -> "ｷﾞ", 'グ' -> "ｸﾞ", 'ゲ' -> "ｹﾞ", 'ゴ' -> "ｺﾞ",
    'ザ' -> "ｻﾞ", 'ジ' -> "ｼﾞ", 'ズ' -> "ｽﾞ", 'ゼ' -> "ｾﾞ", 'ゾ' -> "ｿﾞ",
    'ダ' -> "ﾀﾞ", 'ヂ' -> "ﾁﾞ", 'ヅ' -> "ﾂﾞ", 'デ' -> "ﾃﾞ", 'ド' -> "ﾄﾞ",
    'バ' -> "ﾊﾞ", 'ビ' -> "ﾋﾞ", 'ブ' -> "ﾌﾞ", 'ベ' -> "ﾍﾞ", 'ボ' -> "ﾎﾞ",

    // handakuten
    'パ' -> "ﾊﾟ", 'ピ' -> "ﾋﾟ", 'プ' -> "ﾌﾟ", 'ペ' -> "ﾍﾟ", 'ポ' -> "ﾎﾟ",

    // Special marks
    'ヴ' -> "ｳﾞ",
    'ヵ' -> "ｶ",   // small ka
    'ヶ' -> "ｹ",   // small ke
    '・' -> "･",
    'ー' -> "ｰ",
    '「' -> "｢",
    '」' -> "｣",
    '、' -> "､",
    '。' -> "｡"
  )

  def toHalfWidth(str: String): String =
    str.flatMap { c =>
      // ASCII full-width block FF01–FF5E
      if (c >= '\uFF01' && c <= '\uFF5E')
        ((c - 0xFEE0).toChar).toString

      // Katakana map
      else if (kanaMap.contains(c))
        kanaMap(c)

      else
        (c).toString
    }


